def tr(idioma: str, chave: str, **valores) -> str:
    texto = TEXTOS.get(idioma, {}).get(chave) or TEXTOS["pt"].get(chave) or chave
    try:
        return texto.format(**valores) if valores else texto
    except (KeyError, IndexError, ValueError):
        return texto


def detectar() -> str:
    """Idioma da interface do Windows: pt, es, ru; qualquer outro vira ingles."""
    try:
        import ctypes
        primario = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3FF   # 0x16 pt, 0x0A es, 0x19 ru, 0x09 en
        return {0x16: "pt", 0x0A: "es", 0x19: "ru"}.get(primario, "en")
    except Exception:
        return "en"
